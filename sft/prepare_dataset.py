#!/usr/bin/env python3
"""Validate, deduplicate, and split query-planner SFT data.

Input: raw candidates generated by generate_seed_query_plan_data.py
Output: train/valid Alpaca JSON files plus quality reports for LLaMA-Factory.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
import re
from collections import Counter
from pathlib import Path
from typing import Any

ALLOWED_INTENTS = {
    "definition",
    "mechanism",
    "comparison",
    "application",
    "parameter",
    "challenge",
    "process",
    "advantage",
}

TRAINING_INSTRUCTION = (
    "你是半导体 RAG 系统的 query planner。请把用户问题改写为适合向量库和 BM25 "
    "混合检索的 JSON 查询计划。必须保留专业术语、数值、缩写、材料名、工艺名和比较对象。"
)


def normalize_for_dedupe(text: str) -> str:
    text = text.lower().strip()
    text = re.sub(r"\s+", "", text)
    return re.sub(r"[，。！？、；：,.!?;:\-—_（）()\[\]{}《》<>\"'`]+", "", text)


def sample_key(question: str, primary_query: str) -> str:
    raw = normalize_for_dedupe(question) + "||" + normalize_for_dedupe(primary_query)
    return hashlib.sha1(raw.encode("utf-8")).hexdigest()


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as f:
        for line_no, line in enumerate(f, 1):
            if not line.strip():
                continue
            try:
                item = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"Invalid JSONL at line {line_no}: {exc}") from exc
            rows.append(item)
    return rows


def validate_raw(item: dict[str, Any]) -> tuple[bool, str | None]:
    question = item.get("user_question")
    plan = item.get("query_plan")
    if not isinstance(question, str) or not question.strip():
        return False, "missing_question"
    if not isinstance(plan, dict):
        return False, "missing_query_plan"

    primary = plan.get("primary_query")
    secondaries = plan.get("secondary_queries")
    terms = plan.get("must_keep_terms")
    intent = plan.get("intent")
    aspects = plan.get("answer_aspects")

    if not isinstance(primary, str) or not primary.strip():
        return False, "missing_primary_query"
    if not isinstance(secondaries, list) or not all(isinstance(x, str) and x.strip() for x in secondaries):
        return False, "bad_secondary_queries"
    if not (1 <= len(secondaries) <= 5):
        return False, "bad_secondary_count"
    if not isinstance(terms, list) or len([x for x in terms if isinstance(x, str) and x.strip()]) < 2:
        return False, "bad_must_keep_terms"
    if intent not in ALLOWED_INTENTS:
        return False, "bad_intent"
    if not isinstance(aspects, list) or not any(isinstance(x, str) and x.strip() for x in aspects):
        return False, "bad_answer_aspects"
    return True, None


def to_alpaca(item: dict[str, Any]) -> dict[str, str]:
    output = json.dumps(item["query_plan"], ensure_ascii=False, separators=(",", ":"))
    return {
        "instruction": TRAINING_INSTRUCTION,
        "input": item["user_question"].strip(),
        "output": output,
    }


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")


def build_parser() -> argparse.ArgumentParser:
    root = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw", type=Path, default=root / "results_lite" / "raw_seed_candidates.jsonl")
    parser.add_argument("--output-dir", type=Path, default=root / "dataset")
    parser.add_argument("--valid-ratio", type=float, default=0.1)
    parser.add_argument("--seed", type=int, default=20260630)
    parser.add_argument("--max-samples", type=int, default=None)
    return parser


def main() -> int:
    args = build_parser().parse_args()
    raw_rows = load_jsonl(args.raw)

    valid_rows: list[dict[str, Any]] = []
    reject_reasons: Counter[str] = Counter()
    seen: set[str] = set()
    duplicate_count = 0

    for item in raw_rows:
        ok, reason = validate_raw(item)
        if not ok:
            reject_reasons[reason or "unknown"] += 1
            continue
        key = sample_key(item["user_question"], item["query_plan"]["primary_query"])
        if key in seen:
            duplicate_count += 1
            continue
        seen.add(key)
        valid_rows.append(item)

    if args.max_samples is not None:
        valid_rows = valid_rows[: args.max_samples]

    random.seed(args.seed)
    random.shuffle(valid_rows)

    valid_size = max(1, int(round(len(valid_rows) * args.valid_ratio))) if valid_rows else 0
    validation = valid_rows[:valid_size]
    train = valid_rows[valid_size:]

    train_alpaca = [to_alpaca(x) for x in train]
    valid_alpaca = [to_alpaca(x) for x in validation]
    all_alpaca = [to_alpaca(x) for x in valid_rows]

    intent_counts = Counter(x["query_plan"]["intent"] for x in valid_rows)
    summary = {
        "source": str(args.raw),
        "raw_count": len(raw_rows),
        "valid_count": len(valid_rows),
        "train_count": len(train_alpaca),
        "validation_count": len(valid_alpaca),
        "duplicate_count": duplicate_count,
        "reject_reasons": dict(reject_reasons),
        "intent_counts": dict(intent_counts),
        "valid_ratio": args.valid_ratio,
        "seed": args.seed,
    }

    write_json(args.output_dir / "train_alpaca.json", train_alpaca)
    write_json(args.output_dir / "valid_alpaca.json", valid_alpaca)
    write_json(args.output_dir / "all_alpaca.json", all_alpaca)
    write_json(args.output_dir / "valid_raw.json", validation)
    write_json(args.output_dir / "summary.json", summary)

    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
